-- Run by bin/nvfmt in headless nvim, after the user's init.lua:
--   NVFMT_LIST=<file with one absolute path per line> nvim --headless -c 'lua dofile(vim.env.NVFMT_LUA)'
-- Formats each file with conform's formatters_by_ft (lua/config/format.lua, what <leader>f runs)
-- and lints it with nvim-lint's linters_by_ft (lua/config/lint.lua).
-- Exits 0 clean, 1 lint findings, 2 a formatter failed.

local function say(line) io.stdout:write(line .. '\n') end
local function warn(line) io.stderr:write('nvfmt: ' .. line .. '\n') end

local ok_conform, conform = pcall(require, 'conform')
local ok_lint, lint = pcall(require, 'lint')
if not (ok_conform and ok_lint) then
  warn 'this nvim config has no conform.nvim or nvim-lint'
  vim.cmd 'cquit 2'
end

-- No autocommands: a FileType event would start a language server and treesitter per file.
-- DiagnosticChanged stays on, because it is how a finished linter is noticed.
vim.o.eventignore = 'all,-DiagnosticChanged'
-- A file that is open in another nvim must not raise the swap prompt.
vim.o.swapfile = false
vim.o.undofile = false

-- The same exemption as format_on_save in lua/config/format.lua.
local SKIP_FT = { markdown = true }
local HEAD_LINES = 5

local function generated(buf)
  for _, line in ipairs(vim.api.nvim_buf_get_lines(buf, 0, HEAD_LINES, false)) do
    local lower = line:lower()
    if line:find('GENERATED', 1, true) or lower:find('@generated', 1, true) or lower:find('generated by', 1, true) or lower:find('do not edit', 1, true) then
      return true
    end
  end
  return false
end

---@return 'formatted'|'unchanged'|'failed'
local function format(buf, name)
  local names = conform.list_formatters_for_buffer(buf)
  if #names == 0 then return 'unchanged' end
  for _, formatter in ipairs(names) do
    if not conform.get_formatter_info(formatter, buf).available then
      warn(name .. ': ' .. formatter .. ' is not installed, not formatted')
      return 'unchanged'
    end
  end
  local err
  -- LSP formatting is off: it depends on which servers happen to be attached.
  conform.format({ bufnr = buf, async = false, timeout_ms = 30000, lsp_format = 'never', quiet = true }, function(e) err = e end)
  if err then
    warn(name .. ': ' .. err)
    return 'failed'
  end
  if not vim.bo[buf].modified then return 'unchanged' end
  vim.api.nvim_buf_call(buf, function() vim.cmd 'silent write!' end)
  return 'formatted'
end

---@return vim.Diagnostic[]
local function findings(buf, name)
  local published = 0
  local watch = vim.api.nvim_create_autocmd('DiagnosticChanged', { buffer = buf, callback = function() published = published + 1 end })
  vim.api.nvim_buf_call(buf, function() lint.try_lint() end)
  local started = #lint.get_running(buf)
  local done = vim.wait(30000, function() return published >= started and #lint.get_running(buf) == 0 end, 10)
  vim.api.nvim_del_autocmd(watch)
  if not done then warn(name .. ': the linter did not finish in 30 s') end
  return vim.diagnostic.get(buf)
end

local paths = {}
for path in io.lines(vim.env.NVFMT_LIST) do
  paths[#paths + 1] = path
end

local formatted, found, failed = 0, 0, 0
local last_progress = vim.uv.now()
for i, path in ipairs(paths) do
  -- The real path, because getcwd() is one and ':.' compares text (/var is a link on macOS).
  local name = vim.fn.fnamemodify(vim.uv.fs_realpath(path) or path, ':.')
  local buf = vim.fn.bufadd(path)
  vim.fn.bufload(buf)
  local ft = vim.filetype.match { buf = buf, filename = path } or ''
  if not SKIP_FT[ft] and not generated(buf) then
    vim.bo[buf].filetype = ft
    local result = format(buf, name)
    if result == 'formatted' then
      formatted = formatted + 1
      say('formatted ' .. name)
    elseif result == 'failed' then
      failed = failed + 1
    end
    for _, d in ipairs(findings(buf, name)) do
      found = found + 1
      say(('%s:%d:%d: %s %s %s'):format(name, d.lnum + 1, d.col + 1, d.source or 'lint', d.code or '', d.message))
    end
  end
  vim.api.nvim_buf_delete(buf, { force = true })
  if vim.uv.now() - last_progress > 20000 then
    last_progress = vim.uv.now()
    say(('nvfmt: %d of %d files'):format(i, #paths))
  end
end

say(('nvfmt: %d files, %d formatted, %d lint findings, %d failed'):format(#paths, formatted, found, failed))
vim.cmd('cquit ' .. (failed > 0 and 2 or found > 0 and 1 or 0))
